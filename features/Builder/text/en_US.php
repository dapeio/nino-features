//
// The parts, by what they hold:
//
//   /_admin/builder/label/...     the buttons, the columns of the list and the names of the editor's regions
//   /_admin/builder/hint/...      the sentence a field of a form has to say, which stands behind its question mark
//   /_admin/builder/tree/...      what a frame is called, what the add buttons say, and why a source is red
//   /_admin/builder/menu/...      the titles of the buttons on a frame
//   /_admin/builder/block/...     the names of the blocks every form is drawn in, as block/<name>/label
//   /_admin/builder/group/...     the headings of the groups of a form
//   /_admin/builder/section/...   the fields of the section and row forms
//   /_admin/builder/template/...  the fields of the template form
//   /_admin/builder/col/...       the fields of the column form
//   /_admin/builder/stack/...     the fields of the loop form (the model and the kernel call it a stack)
//   /_admin/builder/loop/...      a loop of a column in the preview - its row and its cell - and the title of its dialog
//   /_admin/builder/component/... the title and the content of the component form
//   /_admin/builder/common/...    what the forms of a section, a column and a component have in common: the toggle of
//                                 the radius of a surface and the hover of a picture
//   /_admin/builder/source/...    the dialog of a source: its tabs, the search, a new key or slot - and the focus of a picture
//   /_admin/builder/value/...     the text of a key, in the language the editor works in
//   /_admin/builder/picture/...   the picture of a slot and its alt text, and what is said of the upload
//   /_admin/builder/focus/...     the nine places of the focus of a picture
//   /_admin/builder/html/...      the HTML+ editor
//   /_admin/builder/option/...    the words of a value of a setting, as <setting>-<value> - of an attribute of a
//                                 component as attribute-<name>-<value>; a value with no words of its own is
//                                 shown as it is, and an empty one as "default" or "none"
//   /_admin/builder/color/...     the grounds a column may paint besides the colours of a section: counter,
//                                 the one that sets it off from its section, and none of its own
//   /_admin/builder/state/...     the states the editor is in: a conflict, a rename, the narrow screen
//   /_admin/builder/viewport/...  the viewports of the preview: the three, and all of them at once (g)
//   /_admin/builder/preview/...   what the marks on a frame of the preview mean
//   /_admin/builder/reason/...    why a section is not read, by the code the Reader gives - and, as pick-*, why a component
//                                 cannot be added where the lightbox was opened, and, as paste-*, why a copy cannot be pasted
//   /_admin/builder/pick/...      the headings of the groups of the lightbox that offers the components
//   /_admin/builder/spacing/...   the words of the box of the spacing: outside, inside, the row, the gap
